#!/usr/bin/env python3
"""Keep the Flipper app version in lockstep with Murmur's version.

Murmur is the source of truth: the `version` field in src-tauri/Cargo.toml. This script
rewrites two generated files and is idempotent:

  companion/flipper/src/version.h      MURMUR_COMPANION_VERSION "..."
  companion/flipper/application.fam    fap_version="..."

Run it from anywhere; both CI and `build.sh` call it before compiling. Pass --check to
verify without writing (CI uses this to catch a forgotten bump).
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
CARGO = ROOT / "src-tauri" / "Cargo.toml"
HEADER = ROOT / "companion" / "flipper" / "src" / "version.h"
MANIFEST = ROOT / "companion" / "flipper" / "application.fam"

HEADER_TEMPLATE = """#pragma once

/* Generated by scripts/sync_version.py from src-tauri/Cargo.toml. Do not edit. */
#define MURMUR_COMPANION_VERSION "{version}"
"""


def app_version() -> str:
    text = CARGO.read_text()
    package = text.split("[package]", 1)
    if len(package) != 2:
        sys.exit("Cargo.toml has no [package] section")
    match = re.search(r'^version\s*=\s*"([^"]+)"', package[1], re.MULTILINE)
    if not match:
        sys.exit("Cargo.toml package has no version")
    return match.group(1)


def desired() -> tuple[str, str, str]:
    version = app_version()
    header = HEADER_TEMPLATE.format(version=version)
    manifest = MANIFEST.read_text()
    updated = re.sub(r'fap_version\s*=\s*"[^"]*"', f'fap_version="{version}"', manifest)
    return version, header, updated


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail instead of writing")
    args = parser.parse_args()

    version, header, manifest = desired()
    current_header = HEADER.read_text() if HEADER.exists() else ""
    current_manifest = MANIFEST.read_text()
    stale = [path for path, before, after in (
        (HEADER, current_header, header),
        (MANIFEST, current_manifest, manifest),
    ) if before != after]

    if args.check:
        if stale:
            for path in stale:
                print(f"out of date: {path.relative_to(ROOT)} (expected {version})")
            return 1
        print(f"companion version sync ok ({version})")
        return 0

    for path, content in ((HEADER, header), (MANIFEST, manifest)):
        path.write_text(content)
    print(f"companion version set to {version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
